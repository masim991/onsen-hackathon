-- 007_ai_logs.sql: additive. (1) ai_logs = one row per AI call (summaries, image classification) for admin review.
-- (2) photo_assets: AI label/confidence + publish_state (license-gated publish rule). Nothing existing is changed or deleted; no photo is published by this migration.
-- AI cannot judge copyright: publish_state 'publish_ok' needs a human-recorded licence (see worker.mjs decidePublish). Public display is unchanged (anon policy still needs published AND license_status='verified').

-- ---------- 1) ai_logs ----------
create table if not exists public.ai_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind text not null check (kind in ('notice_summary','change_summary','image_classify')),
  facility_id text references public.onsen_facilities(id) on delete set null,
  notice_id bigint references public.facility_notices(id) on delete set null,
  photo_id bigint references public.photo_assets(id) on delete set null,
  change_id bigint references public.facility_changes(id) on delete set null,
  model text not null,
  input_digest jsonb not null default '{}'::jsonb,           -- {sha256, excerpt (<=200 chars), chars|bytes}; never a full page
  output jsonb not null default '{}'::jsonb,                 -- {summary_ko, confidence, labels[], reason}
  status text not null check (status in ('ok','error','skipped','mock')),
  tokens_in int not null default 0,
  tokens_out int not null default 0,
  error text check (char_length(error) <= 300),              -- redacted by the worker, no secrets
  review_status text not null default 'unreviewed' check (review_status in ('unreviewed','accepted','rejected','edited')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  reviewed_summary_ko text check (char_length(reviewed_summary_ko) <= 600)
);
create index if not exists ai_logs_created_idx on public.ai_logs (created_at desc);
create index if not exists ai_logs_kind_status_idx on public.ai_logs (kind, status);
create index if not exists ai_logs_unreviewed_idx on public.ai_logs (created_at desc) where review_status = 'unreviewed';
create index if not exists ai_logs_facility_idx on public.ai_logs (facility_id);
create index if not exists ai_logs_notice_idx on public.ai_logs (notice_id);
create index if not exists ai_logs_photo_idx on public.ai_logs (photo_id);
create index if not exists ai_logs_change_idx on public.ai_logs (change_id);
create index if not exists ai_logs_reviewed_by_idx on public.ai_logs (reviewed_by);

alter table public.ai_logs enable row level security;
revoke all on public.ai_logs from anon, authenticated;
grant select on public.ai_logs to authenticated;
grant update (review_status, reviewed_by, reviewed_at, reviewed_summary_ko) on public.ai_logs to authenticated;
-- inserts: service role only (it bypasses RLS and holds its own grants); no insert policy / grant for anon or authenticated.

drop policy if exists "admin select" on public.ai_logs;
create policy "admin select" on public.ai_logs for select to authenticated using ((select public.is_admin()));
drop policy if exists "admin review" on public.ai_logs;
create policy "admin review" on public.ai_logs for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()) and reviewed_by = (select auth.uid()));

-- Review in one transaction (security invoker: the caller's own grants + RLS apply, so a non-admin fails).
-- accepted | rejected | edited(+summary). edited notice_summary also updates facility_notices.summary_ko.
-- rejected notice_summary: the AI text is removed from the notice again (and the notice is un-published) if it is still the stored text.
create or replace function public.ai_log_review(p_id bigint, p_status text, p_summary text default null) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare r public.ai_logs; s text := nullif(btrim(coalesce(p_summary, '')), '');
begin
  if not (select public.is_admin()) then raise exception 'admin only' using errcode = '42501'; end if;
  if p_status not in ('accepted','rejected','edited') then raise exception 'bad status'; end if;
  if p_status = 'edited' and (s is null or char_length(s) > 600) then raise exception 'summary required (max 600 chars)'; end if;
  update public.ai_logs
     set review_status = p_status, reviewed_by = (select auth.uid()), reviewed_at = now(),
         reviewed_summary_ko = case when p_status = 'edited' then s else null end
   where id = p_id returning * into r;
  if not found then raise exception 'not found'; end if;
  if r.kind = 'notice_summary' and r.notice_id is not null then
    if p_status = 'edited' then
      update public.facility_notices set summary_ko = s where id = r.notice_id;
    elsif p_status = 'rejected' then
      update public.facility_notices set summary_ko = null, published = false
       where id = r.notice_id and summary_ko is not distinct from (r.output->>'summary_ko');
    end if;
  end if;
  return jsonb_build_object('id', r.id, 'review_status', r.review_status);
end $$;
revoke all on function public.ai_log_review(bigint, text, text) from public, anon;
grant execute on function public.ai_log_review(bigint, text, text) to authenticated;

-- ---------- 2) photo_assets: AI label + licence-gated publish state ----------
alter table public.photo_assets
  add column if not exists ai_label text check (ai_label in ('onsen_bath','exterior','room','food','logo','map_doc','other')),
  add column if not exists ai_confidence numeric(4,3) check (ai_confidence between 0 and 1),
  add column if not exists ai_reason text check (char_length(ai_reason) <= 300),
  add column if not exists ai_checked_at timestamptz,
  add column if not exists license_source text check (license_source in ('official','unknown','commons','owned')),  -- set by a human/importer, never by the AI
  add column if not exists license_note text check (char_length(license_note) <= 300),                              -- recorded licence text (needed for 'commons')
  add column if not exists publish_state text not null default 'unchecked'
    check (publish_state in ('unchecked','publish_ok','hold_license','logo_review','logo_approved','approved','rejected','not_published','check_failed'));
create index if not exists photo_assets_state_idx on public.photo_assets (publish_state) where publish_state in ('hold_license','logo_review');
create index if not exists photo_assets_unchecked_idx on public.photo_assets (discovered_at) where ai_checked_at is null and not published;

-- Admins may additionally set publish_state (guarded below). ai_* / license_source / license_note stay read-only for them (worker / importer own them).
grant update (publish_state) on public.photo_assets to authenticated;

-- Admin transitions only: hold_license|logo_review -> approved (needs license_status=verified) | logo_approved (logo only, never published) | rejected.
-- published=true always needs license_status='verified' for admins (same rule the UI and the public policy already apply).
-- Service role / SQL editor have no auth.uid() and are unrestricted (the worker applies the rule table in code).
create or replace function public.photo_assets_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if (select auth.uid()) is null then return new; end if;
  if new.published and new.license_status is distinct from 'verified' then raise exception 'publishing needs license_status=verified'; end if;
  if new.publish_state is distinct from old.publish_state and not (
       (old.publish_state = 'hold_license' and new.publish_state = 'approved' and new.license_status = 'verified')
    or (old.publish_state = 'logo_review' and new.publish_state = 'logo_approved' and not new.published)
    or (old.publish_state in ('hold_license','logo_review') and new.publish_state = 'rejected' and not new.published)) then
    raise exception 'publish_state change % -> % is not allowed', old.publish_state, new.publish_state;
  end if;
  return new;
end $$;
revoke all on function public.photo_assets_guard() from public, anon, authenticated;
drop trigger if exists photo_assets_guard on public.photo_assets;
create trigger photo_assets_guard before update on public.photo_assets
  for each row execute function public.photo_assets_guard();
