-- 001_monitor.sql: official-site monitoring (additive, idempotent). Existing onsen_* tables are NOT altered.
-- Worker uses the service role (bypasses RLS). anon/authenticated get only what is granted below.

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin() returns boolean
language sql stable security invoker set search_path = '' as  -- invoker (not definer): the advisor flags definer; admins has an own-row SELECT policy instead
$$ select exists (select 1 from public.admins a where a.user_id = (select auth.uid())) $$;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create table if not exists public.monitor_targets (
  id bigint generated by default as identity primary key,
  facility_id text not null references public.onsen_facilities(id) on delete cascade,
  kind text not null check (kind in ('notice','price_hours','photo')),
  url text not null,
  interval_minutes int not null default 360 check (interval_minutes >= 30),
  next_check_at timestamptz not null default now(),
  last_checked_at timestamptz,
  last_status text,
  fail_count int not null default 0,
  enabled boolean not null default true,
  unique (facility_id, kind, url)
);
create index if not exists monitor_targets_facility_idx on public.monitor_targets (facility_id);
create index if not exists monitor_targets_next_idx on public.monitor_targets (next_check_at) where enabled;

create table if not exists public.monitor_jobs (
  id bigint generated by default as identity primary key,
  target_id bigint not null references public.monitor_targets(id) on delete cascade,
  facility_id text not null references public.onsen_facilities(id) on delete cascade,
  kind text not null check (kind in ('notice','price_hours','photo')),
  status text not null default 'queued' check (status in ('queued','running','ok','failed','skipped')),
  attempts int not null default 0,
  run_after timestamptz not null default now(),
  worker text,
  started_at timestamptz,
  finished_at timestamptz,
  error text
);
create index if not exists monitor_jobs_target_idx on public.monitor_jobs (target_id);
create index if not exists monitor_jobs_facility_idx on public.monitor_jobs (facility_id);
create index if not exists monitor_jobs_status_run_idx on public.monitor_jobs (status, run_after);

create table if not exists public.monitor_snapshots (
  target_id bigint not null references public.monitor_targets(id) on delete cascade,
  content_hash text not null,
  excerpt text check (char_length(excerpt) <= 2000),
  fetched_at timestamptz not null default now(),
  primary key (target_id, content_hash)
);
create index if not exists monitor_snapshots_fetched_idx on public.monitor_snapshots (fetched_at);

create table if not exists public.facility_changes (
  id bigint generated by default as identity primary key,
  facility_id text not null references public.onsen_facilities(id) on delete cascade,
  field text not null,
  old_value jsonb,
  new_value jsonb,
  evidence text,
  source_url text,
  status text not null check (status in ('auto_applied','pending_review','rejected')),
  dedupe_key text not null unique,
  created_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id) on delete set null
);
create index if not exists facility_changes_facility_idx on public.facility_changes (facility_id);
create index if not exists facility_changes_status_idx on public.facility_changes (status, created_at);
create index if not exists facility_changes_reviewed_by_idx on public.facility_changes (reviewed_by);

create table if not exists public.facility_notices (
  id bigint generated by default as identity primary key,
  facility_id text not null references public.onsen_facilities(id) on delete cascade,
  source_url text not null,
  content_hash text not null,
  title text,
  notice_date date,
  original_excerpt text check (char_length(original_excerpt) <= 2000),
  summary_ko text,
  published boolean not null default false,
  detected_at timestamptz not null default now(),
  unique (facility_id, content_hash)
);

create table if not exists public.photo_assets (
  id bigint generated by default as identity primary key,
  facility_id text not null references public.onsen_facilities(id) on delete cascade,
  image_url text not null,
  sha256 text not null,
  license_status text not null default 'unverified',
  published boolean not null default false,
  discovered_at timestamptz not null default now(),
  unique (facility_id, sha256)
);

create table if not exists public.monitor_logs (
  id bigserial primary key,
  ts timestamptz not null default now(),
  level text not null,
  facility_id text,
  job_id bigint,
  job_kind text,
  result text,
  error_cause text,
  meta jsonb
);
create index if not exists monitor_logs_ts_idx on public.monitor_logs (ts);
create index if not exists monitor_logs_facility_idx on public.monitor_logs (facility_id);

create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  ts timestamptz not null default now(),
  model text not null,
  input_tokens int not null default 0,
  output_tokens int not null default 0,
  est_cost_usd numeric(10,6) not null default 0,
  facility_id text
);
create index if not exists ai_usage_ts_idx on public.ai_usage (ts);

-- ---- RLS: on everywhere, no anon write anywhere ----
alter table public.admins enable row level security;
alter table public.monitor_targets enable row level security;
alter table public.monitor_jobs enable row level security;
alter table public.monitor_snapshots enable row level security;
alter table public.facility_changes enable row level security;
alter table public.facility_notices enable row level security;
alter table public.photo_assets enable row level security;
alter table public.monitor_logs enable row level security;
alter table public.ai_usage enable row level security;

revoke all on public.admins, public.monitor_targets, public.monitor_jobs, public.monitor_snapshots,
  public.facility_changes, public.facility_notices, public.photo_assets, public.monitor_logs, public.ai_usage
  from anon, authenticated;
revoke all on sequence public.monitor_logs_id_seq from anon, authenticated;

grant select on public.admins, public.monitor_targets, public.monitor_jobs, public.monitor_snapshots,
  public.facility_changes, public.facility_notices, public.photo_assets, public.monitor_logs, public.ai_usage to authenticated;
grant select on public.facility_notices, public.photo_assets to anon;
grant insert on public.monitor_jobs to authenticated;                         -- re-check requests
grant update (status, reviewed_by) on public.facility_changes to authenticated;
grant update (published, summary_ko) on public.facility_notices to authenticated;           -- admin approval
grant update (license_status, published) on public.photo_assets to authenticated;           -- admin approval

do $$
declare t text;
begin
  foreach t in array array['monitor_targets','monitor_jobs','monitor_snapshots','facility_changes','facility_notices','photo_assets','monitor_logs','ai_usage'] loop
    execute format('drop policy if exists "admin select" on public.%I', t);
    execute format('create policy "admin select" on public.%I for select to authenticated using ((select public.is_admin()))', t);
  end loop;
end $$;

drop policy if exists "own admin row" on public.admins;
create policy "own admin row" on public.admins for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "admin recheck" on public.monitor_jobs;
create policy "admin recheck" on public.monitor_jobs for insert to authenticated
  with check ((select public.is_admin()) and status = 'queued');

drop policy if exists "admin review" on public.facility_changes;
create policy "admin review" on public.facility_changes for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "admin approve" on public.facility_notices;
create policy "admin approve" on public.facility_notices for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "admin approve" on public.photo_assets;
create policy "admin approve" on public.photo_assets for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "public published notices" on public.facility_notices;
create policy "public published notices" on public.facility_notices for select to anon, authenticated
  using (published);

drop policy if exists "public verified photos" on public.photo_assets;
create policy "public verified photos" on public.photo_assets for select to anon, authenticated
  using (published and license_status = 'verified');

-- ---- service-role-only helpers (worker) ----
create or replace function public.monitor_prune(days int default 90) returns jsonb
language plpgsql set search_path = '' as $$
declare l int; s int; j int;
begin
  delete from public.monitor_logs where ts < now() - make_interval(days => days);
  get diagnostics l = row_count;
  delete from public.monitor_snapshots s2 where s2.fetched_at < now() - make_interval(days => days)
    and exists (select 1 from public.monitor_snapshots n where n.target_id = s2.target_id and n.fetched_at > s2.fetched_at);
  get diagnostics s = row_count;
  delete from public.monitor_jobs where status in ('ok','failed','skipped') and finished_at < now() - make_interval(days => days);
  get diagnostics j = row_count;
  return jsonb_build_object('logs', l, 'snapshots', s, 'jobs', j);
end $$;

create or replace function public.monitor_enqueue_due() returns int
language plpgsql set search_path = '' as $$
declare n int;
begin
  insert into public.monitor_jobs (target_id, facility_id, kind)
  select t.id, t.facility_id, t.kind from public.monitor_targets t
  where t.enabled and t.next_check_at <= now()
    and not exists (select 1 from public.monitor_jobs j where j.target_id = t.id and j.status in ('queued','running'));
  get diagnostics n = row_count;
  return n;
end $$;

-- SKIP LOCKED claim; running jobs older than 20 min are treated as crashed and re-claimable.
create or replace function public.monitor_claim_jobs(p_worker text, p_limit int default 20) returns jsonb
language plpgsql set search_path = '' as $$
declare r jsonb;
begin
  update public.monitor_jobs set status = 'queued' where status = 'running' and started_at < now() - interval '20 minutes';
  with pick as (
    select id from public.monitor_jobs where status = 'queued' and run_after <= now()
    order by run_after, id limit p_limit for update skip locked
  ), upd as (
    update public.monitor_jobs j set status = 'running', worker = p_worker, started_at = now(), attempts = j.attempts + 1
    from pick where j.id = pick.id returning j.*
  )
  select coalesce(jsonb_agg(to_jsonb(upd) || jsonb_build_object('url', t.url)), '[]'::jsonb)
    into r from upd join public.monitor_targets t on t.id = upd.target_id;
  return r;
end $$;

-- Only writes new keys under record->'monitor' (price|hours); original fields are never touched.
create or replace function public.monitor_apply_record(p_fid text, p_key text, p_val jsonb) returns int
language plpgsql set search_path = '' as $$
declare n int;
begin
  if p_key not in ('price','hours') then raise exception 'key not allowed'; end if;
  update public.onsen_facilities
     set record = jsonb_set(coalesce(record, '{}'::jsonb), '{monitor}',
                            coalesce(record->'monitor', '{}'::jsonb) || jsonb_build_object(p_key, p_val), true)
   where id = p_fid;
  get diagnostics n = row_count;
  return n;
end $$;

revoke all on function public.monitor_prune(int), public.monitor_enqueue_due(), public.monitor_claim_jobs(text, int),
  public.monitor_apply_record(text, text, jsonb) from public, anon, authenticated;
grant execute on function public.monitor_prune(int), public.monitor_enqueue_due(), public.monitor_claim_jobs(text, int),
  public.monitor_apply_record(text, text, jsonb) to service_role;
